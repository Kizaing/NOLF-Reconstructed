# =========================================================================================================== wave plan
def write_wave(U, S, W):
    units = U['units']
    byname = {u['unit']: u for u in units}
    funcs = S['funcs']
    names = seed_names()
    starts = [u['lo'] for u in units]

    def uidx(a):
        i = bisect.bisect_right(starts, a) - 1
        return i if i >= 0 and units[i]['lo'] <= a < units[i]['hi'] else None

    # call matrix, fan-in per function
    M = collections.Counter()
    fanin = collections.defaultdict(set)
    for f in funcs:
        i = uidx(f['addr'])
        if i is None:
            continue
        for c in f['calls']:
            j = uidx(c)
            if j is not None and j != i:
                M[(i, j)] += 1
                fanin[c].add(i)
    pk_of = {}
    for p in W['packages']:
        for un in p['units']:
            pk_of[un] = p['id']
    # shared globals (>= 4 units)
    gu = collections.defaultdict(collections.Counter)
    for f in funcs:
        i = uidx(f['addr'])
        if i is None or not units[i]['src']:
            continue
        for v in f['drefs'] + f['brefs']:
            if v >= 0x1004d5a0:
                gu[v][units[i]['unit']] += 1
    gnames = {}
    for fl in glob.glob(os.path.join(REPO, 'src', 'd3dren', 'seed', '*.cpp')) + glob.glob(os.path.join(REPO, 'include', 'd3dren', '*.h')):
        lines = open(fl, encoding='utf-8', errors='replace').read().split('\n')
        for k, l in enumerate(lines):
            m = re.match(r'\s*//\s*GLOBAL:\s*D3DREN\s+0x([0-9a-fA-F]{8})', l)
            if m and k + 1 < len(lines):
                mm = re.search(r'([A-Za-z_]\w*)\s*(?:\(|;|=|\[)', lines[k + 1].replace('extern', ''))
                if mm:
                    gnames[int(m.group(1), 16)] = mm.group(1)
    K = W['K']
    pk = W['packages']
    tb = sum(p['bytes'] for p in pk)
    tf = sum(p['nf'] for p in pk)
    tn = sum(p['nontrivial'] for p in pk)
    L = []
    w = L.append
    w('# d3d.ren decompilation: work packages (wave plan)')
