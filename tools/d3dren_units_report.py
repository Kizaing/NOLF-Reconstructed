def hx(v):
    return '%08x' % v


def load():
    U = json.load(open(os.path.join(OUT, 'units.json')))
    S = json.load(open(os.path.join(OUT, 'scan.json')))
    W = json.load(open(os.path.join(OUT, 'waves.json')))
    ext = json.load(open(os.path.join(OUT, 'units_ext.json')))
    for u in U['units']:
        u.update(ext[u['unit']])
        u['m'] = dict(u['m'])
    return U, S, W


def seed_names():
    """address -> name from the seed sources (// FUNCTION: D3DREN 0xADDR followed by the definition)"""
    names = {}
    for f in glob.glob(os.path.join(REPO, 'src', 'd3dren', 'seed', '*.cpp')):
        lines = open(f, encoding='utf-8', errors='replace').read().split('\n')
        for i, l in enumerate(lines):
            m = re.match(r'\s*//\s*(?:FUNCTION|STUB):\s*D3DREN\s+0x([0-9a-fA-F]{8})\s*(\S*)', l)
            if not m:
                continue
            a = int(m.group(1), 16)
            for k in range(i + 1, min(i + 6, len(lines))):
                t = lines[k].strip()
                if not t or t.startswith('//'):
                    continue
                mm = re.search(r'([~\w:]+)\s*\(', t)
                if mm and a not in names:
                    names[a] = mm.group(1)
                break
    return names


def seed_flag_table(units):
    """flags of the seed sources (src/d3dren/seed/*.cpp) by the kind of region their annotated addresses fall in"""
    starts = [u['lo'] for u in units]
    cnt = collections.defaultdict(collections.Counter)
    for fl in glob.glob(os.path.join(REPO, 'src', 'd3dren', 'seed', '*.cpp')):
        t = open(fl, encoding='utf-8', errors='replace').read()
        m = re.search(r'// FLAGS: (.*)', t)
        flags = m.group(1).strip() if m else '(default /O2)'
        for a in set(re.findall(r'(?:FUNCTION|STUB): D3DREN 0x(1[0-9a-fA-F]{7})', t)):
            a = int(a, 16)
            i = bisect.bisect_right(starts, a) - 1
            if i >= 0 and units[i]['lo'] <= a < units[i]['hi'] and units[i]['kind'] in 'AP':
                cnt[units[i]['kind']][flags] += 1
    return cnt


def md_table(rows, header):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '|'.join('---' for _ in header) + '|']
    for r in rows:
        out.append('| ' + ' | '.join(str(c) for c in r) + ' |')
    return '\n'.join(out)


